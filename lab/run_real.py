#!/usr/bin/env python3
"""run_real.py - end-to-end REAL-tool test pipeline:

mock target  ->  recording tee proxy  ->  actual php2shell CLI (detect,
preflight, exploit)  ->  recorded wire bytes -> attack-real.pcap ->
offline Suricata -> alert report.

Environment:
  P2S_REPO       upstream clone (default: ../php2shell)
  P2S_PY         python inside the upstream venv (default: $P2S_REPO/.venv/bin/python)
  SURICATA_BIN   suricata binary   (default: suricata)
  SURICATA_CONF  base suricata.yaml (default: lab/suricata.yaml if present)
  OUT_DIR        directory for suricata results (default: <repo>/results)
"""
import json
import os
import signal
import subprocess
import sys
import time

import tempfile as _tempfile

LAB = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(LAB)
REPO = os.environ.get("P2S_REPO", os.path.join(ROOT, "php2shell"))
PY = os.environ.get("P2S_PY", os.path.join(REPO, ".venv", "bin", "python"))
URL = "http://127.0.0.1:8095/index.php"

def out_tmpdirname():
    global _T
    try:
        return _T
    except NameError:
        _T = _tempfile.mkdtemp(prefix="p2slab-")
        return _T

def sh(cmd, **kw):
    print(f"[run] {' '.join(cmd)}", flush=True)
    return subprocess.run(cmd, capture_output=True, text=True, **kw)

def main():
    recorded = os.path.join(LAB, "recorded.jsonl")
    procs = {}
    try:
        procs["mock"] = subprocess.Popen([sys.executable, os.path.join(LAB, "mock_target.py")],
                                         stdout=subprocess.DEVNULL)
        time.sleep(0.5)
        os.chdir(LAB)
        if os.path.exists("recorded.jsonl"):
            os.unlink("recorded.jsonl")
        open("recorded.jsonl", "w").close()
        procs["tee"] = subprocess.Popen([sys.executable, os.path.join(LAB, "tee_proxy.py")], cwd=LAB)
        time.sleep(0.5)

        stages = [
            ["detect", "-u", URL],
            ["preflight", "-u", URL],
            ["exploit", "-u", URL, "--force", "--yes",
             "--exploit-profile", "bookworm",
             "-c", "id>/out/p1",
             "--fetch", "http://127.0.0.1:8095/out/p1"],
        ]
        n = 0
        for stage in stages:
            r = subprocess.run([PY, os.path.join(REPO, "php2shell.py")] + stage,
                               capture_output=True, text=True, cwd=LAB, timeout=600)
            print(f"\n===== php2shell {stage[0].upper()} rc={r.returncode} =====")
            out = (r.stdout + r.stderr).strip()
            print("\n".join(out.splitlines()[:40]))
            n = r.returncode
        time.sleep(1.0)
    finally:
        for name, p in procs.items():
            p.send_signal(signal.SIGINT)
        for name, p in procs.items():
            try:
                p.wait(timeout=5)
            except subprocess.TimeoutExpired:
                p.kill()
        time.sleep(0.5)

    # ---- build real pcap ----
    sys.path.insert(0, LAB)
    from pcap_build import write_pcap  # noqa: E402
    streams = []
    for i, line in enumerate(open(recorded)):
        rec = json.loads(line)
        streams.append({
            "cip": "203.0.113.77", "cport": 40000 + i,
            "sip": "198.51.100.10", "sport": 80,
            "req": rec["req"].encode("latin1"),
            "resp": rec["resp"].encode("latin1"),
        })
    pcap = os.path.join(LAB, "attack-real.pcap")
    write_pcap(pcap, streams)
    print(f"\n[run] recorded {len(streams)} connections -> {pcap}")

    out = os.path.join(os.environ.get("OUT_DIR", os.path.join(ROOT, "results")), "real")
    subprocess.run(["rm", "-rf", out], check=True)
    os.makedirs(out, exist_ok=True)

    # ---- suricata offline ----
    # if SURICATA_CONF is a raw base yaml (not lab-generated), derive a
    # patched lab config first (HOME_NET any, body limits, checksum off)
    base = os.environ.get("SURICATA_CONF", os.path.join(LAB, "suricata.yaml"))
    conf = base
    marker = "# lab-config generated by make_lab_config.py"
    generated = base and os.path.exists(base) and marker in open(base).read()
    if not generated:
        gen = os.path.join(out_tmpdirname(), "suricata-lab.yaml")
        mk = subprocess.run([sys.executable, os.path.join(LAB, "make_lab_config.py")],
                            capture_output=True, text=True,
                            env={**os.environ,
                                 "SURICATA_CONF": base or "/etc/suricata/suricata.yaml",
                                 "LAB_CONF_OUT": gen})
        print(mk.stdout.strip() or mk.stderr.strip())
        conf = gen
    r = sh([os.environ.get("SURICATA_BIN", "suricata"),
            "-c", conf,
            "-S", os.path.join(ROOT, "rules/php2shell.rules"),
            "-r", pcap, "-l", out, "-k", "none"], env=dict(os.environ))
    print([l for l in r.stdout.splitlines() if "packets" in l])
    c = {}
    for line in open(os.path.join(out, "eve.json")):
        e = json.loads(line)
        if e.get("event_type") == "alert":
            c[e["alert"]["signature_id"]] = c.get(e["alert"]["signature_id"], 0) + 1
    print("alerts-by-sid:", dict(sorted(c.items())), "total:", sum(c.values()))

if __name__ == "__main__":
    main()
