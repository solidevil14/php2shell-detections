#!/usr/bin/env python3
"""make_lab_config.py - generate a lab-tuned suricata.yaml from the system
default config (no root needed; output is a standalone file).

Environment:
  SURICATA_CONF  base config   (default: /etc/suricata/suricata.yaml)
  LAB_CONF_OUT   output path   (default: <repo>/lab/suricata-lab.yaml)

Patches applied (see docs/TUNING.md for rationale):
  HOME_NET / EXTERNAL_NET       -> [0.0.0.0/0]   (lab synthetic addresses)
  request-body-limit            -> 32mb          (chain sends 12MB fields)
  response-body-limit           -> 1mb
  checksum-validation           -> no            (synthetic pcap checksums)
"""
import os
import re

BASE = os.environ.get("SURICATA_CONF", "/etc/suricata/suricata.yaml")
OUT = os.environ.get("LAB_CONF_OUT",
                     os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                  "suricata-lab.yaml"))


def main():
    src = open(BASE).read()

    src = re.sub(r"^(\s+)HOME_NET:.*$", r'\1HOME_NET: "[0.0.0.0/0]"', src, flags=re.M)
    src = re.sub(r"^(\s+)EXTERNAL_NET:.*$", r'\1EXTERNAL_NET: "[0.0.0.0/0]"', src, flags=re.M)
    src = re.sub(r"^(\s*)request-body-limit:.*$", r"\1request-body-limit: 32mb", src, flags=re.M)
    src = re.sub(r"^(\s*)response-body-limit:.*$", r"\1response-body-limit: 1mb", src, flags=re.M)
    src = re.sub(r"^(\s*)checksum-validation:.*$", r"\1checksum-validation: no", src, flags=re.M)

    # If the base config lives outside /etc/suricata (rootless extractions,
    # custom rootfs), rewrite the auxiliary config paths next to it.
    base_dir = os.path.dirname(os.path.abspath(BASE))
    for key in ("classification-file", "reference-config-file", "threshold-file",
                "classification",):
        m = re.search(rf"^(\s*){key}: *(\S*)\s*$", src, flags=re.M)
        if not m:
            continue
        path = m.group(2).strip('"')
        if path and not os.path.exists(path):
            candidate = os.path.join(base_dir, os.path.basename(path))
            if os.path.exists(candidate):
                src = re.sub(rf"^(\s*){key}: *(\S*)\s*$",
                             rf'\g<1>{key}: "{candidate}"', src, flags=re.M)

    with open(OUT, "w") as f:
        f.write("# lab-config generated by make_lab_config.py (do not edit; re-run to regenerate)\n\n" + src)
    print(f"[ok] lab config written: {OUT} (base: {BASE})")

    # sanity echo
    for key in ("HOME_NET", "request-body-limit: 32mb", "checksum-validation: no"):
        for line in src.splitlines():
            if line.lstrip().startswith(key):
                print("    ", line.strip())
                break


if __name__ == "__main__":
    main()
